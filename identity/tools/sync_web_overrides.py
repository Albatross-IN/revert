#!/usr/bin/env python3
"""Regenerate ``static/src/replace/*.js`` from the Odoo ``web`` sources.

The web-client URL prefix ("/odoo") is hard-coded inside two core modules
that cannot be patched from outside (module-private functions):
``web/static/src/core/browser/router.js`` and
``web/static/src/webclient/menus/menu_helpers.js``.  Identity ships
prefix-aware copies of both, swapped in through ``('replace', ...)`` asset
directives and aliased to the original module names.

Odoo keeps changing these files, so the copies are *generated*: each edit
below must match exactly once, otherwise the script stops and says which
anchor moved.  Run it after updating Odoo and review the diff::

    python3 tools/sync_web_overrides.py /opt/odoo20/odoo20/addons/web
"""
import pathlib
import sys

MODULE_DIR = pathlib.Path(__file__).resolve().parent.parent
REPLACE_DIR = MODULE_DIR / 'static' / 'src' / 'replace'

ROUTER_HEADER = '''/** @odoo-module alias=@web/core/browser/router default=false */
/*
 * Identity: GENERATED by tools/sync_web_overrides.py from
 * web/static/src/core/browser/router.js (Odoo 20.0) -- do not edit by hand.
 * The hard-coded "/odoo" web-client prefix is replaced by the configurable
 * one exposed in session.identity.web_prefix.  Installed through the
 * ('replace', ...) asset directives in __manifest__.py.
 */
'''

ROUTER_PRELUDE = '''import { session } from "@web/session";

/** the URL prefix of the web client ("odoo" in stock Odoo) */
export const WEB_PREFIX = (session.identity && session.identity.web_prefix) || "odoo";
'''

# (old, new): each ``old`` must occur exactly once in the source file
ROUTER_EDITS = [
    # relative imports would resolve against the identity module
    ('import { omit, pick } from "../utils/objects";',
     'import { omit, pick } from "@web/core/utils/objects";'),
    ('import { compareUrls, objectToUrlEncodedString } from "../utils/urls";',
     'import { compareUrls, objectToUrlEncodedString } from "@web/core/utils/urls";'),
    ('import { location, browser } from "./browser";',
     'import { location, browser } from "@web/core/browser/browser";\n' + ROUTER_PRELUDE),
    # URLs built by the router
    ('return isScopedApp() ? "scoped_app" : "odoo";',
     'return isScopedApp() ? "scoped_app" : WEB_PREFIX;'),
    # URLs parsed by the router: branded, stock (before the redirect) and scoped apps
    ('if (["odoo", "scoped_app"].includes(prefix)) {',
     'if ([WEB_PREFIX, "odoo", "scoped_app"].includes(prefix)) {'),
    ('const url = location.href.replace("/scoped_app", "/odoo");',
     'const url = location.href.replace("/scoped_app", `/${WEB_PREFIX}`);'),
    # in-app navigation of <a href> clicks
    ('''            location.pathname.startsWith("/odoo") &&
            (["/web", "/odoo"].includes(url.pathname) || url.pathname.startsWith("/odoo/")) &&''',
     '''            (location.pathname.startsWith("/odoo") || location.pathname.startsWith(`/${WEB_PREFIX}`)) &&
            (["/web", "/odoo", `/${WEB_PREFIX}`].includes(url.pathname) ||
                url.pathname.startsWith("/odoo/") ||
                url.pathname.startsWith(`/${WEB_PREFIX}/`)) &&'''),
    ('            if (url.pathname.startsWith("/odoo") && url.hash) {',
     '            if ((url.pathname.startsWith("/odoo") || url.pathname.startsWith(`/${WEB_PREFIX}`)) && url.hash) {'),
]

MENU_HEADER = '''/** @odoo-module alias=@web/webclient/menus/menu_helpers default=false */
/*
 * Identity: GENERATED by tools/sync_web_overrides.py from
 * web/static/src/webclient/menus/menu_helpers.js (Odoo 20.0) -- do not edit
 * by hand.  Menu hrefs use the configurable web-client prefix instead of
 * "/odoo".  See __manifest__.py ('replace', ...).
 */
import { WEB_PREFIX } from "@web/core/browser/router";
'''

MENU_EDITS = [
    ('let href = `/odoo/${menuItem.actionPath || "action-" + menuItem.actionID}`;',
     'let href = `/${WEB_PREFIX}/${menuItem.actionPath || "action-" + menuItem.actionID}`;'),
]

TARGETS = [
    ('core/browser/router.js', 'router.js', ROUTER_HEADER, ROUTER_EDITS),
    ('webclient/menus/menu_helpers.js', 'menu_helpers.js', MENU_HEADER, MENU_EDITS),
]


def generate(web_dir):
    src_dir = pathlib.Path(web_dir) / 'static' / 'src'
    for src_rel, out_name, header, edits in TARGETS:
        source = (src_dir / src_rel).read_text()
        for old, new in edits:
            count = source.count(old)
            if count != 1:
                sys.exit(f'{src_rel}: anchor found {count} times, update tools/sync_web_overrides.py:\n{old}')
            source = source.replace(old, new)
        # lines still building stock URLs (lines also handling WEB_PREFIX are the
        # intentional "/odoo" backward-compatibility checks)
        leftovers = [line.strip() for line in source.splitlines()
                     if ('"/odoo' in line or "'/odoo" in line) and 'WEB_PREFIX' not in line
                     and not line.strip().startswith(('url.pathname.startsWith("/odoo/")', '//', '*'))]
        (REPLACE_DIR / out_name).write_text(header + source)
        print(f'wrote static/src/replace/{out_name}')
        for line in leftovers:
            print(f'  note: remaining stock prefix reference: {line}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    generate(sys.argv[1])
