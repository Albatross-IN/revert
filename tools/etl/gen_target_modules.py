#!/usr/bin/env python3
"""Derive the frozen v20 target module list from the SOURCE snapshot (never hand-typed,
so a cutover replay from a fresh dump always regenerates it):

    installed-on-18  minus  MERGED_MODULES (config.py)  =  target_modules_prod.txt

Refuses to write the file if any resulting name has no directory in the v20 addons path.
Run:  /opt/odoo20/odoo20-venv/bin/python tools/etl/gen_target_modules.py
"""
import os
import sys

import psycopg2

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from tools.etl import config  # noqa: E402

V20_ADDON_DIRS = [
    "/opt/odoo20/odoo20/addons",
    "/opt/odoo20/odoo20/odoo/addons",
    "/opt/odoo20/ent",
    "/opt/odoo20/custom/revert_20",
]
OUT = config.TARGET_MODULES_FILE


def main():
    with psycopg2.connect(dbname=config.SRC_DB) as conn, conn.cursor() as cr:
        cr.execute("SELECT name FROM ir_module_module WHERE state = 'installed' ORDER BY name")
        installed = [r[0] for r in cr.fetchall()]
    print(f"source {config.SRC_DB}: {len(installed)} installed modules")

    target, merged = list(config.EXTRA_MODULES), []
    for name in installed:
        if name in config.MERGED_MODULES:
            merged.append(f"{name} -> {config.MERGED_MODULES[name]}")
        else:
            target.append(name)

    missing = [m for m in target if not any(os.path.isdir(os.path.join(d, m)) for d in V20_ADDON_DIRS)]
    if missing:
        print("FATAL: these modules have no v20 directory (extend MERGED_MODULES in config.py"
              " or install/port the module):", file=sys.stderr)
        for m in missing:
            print(f"  - {m}", file=sys.stderr)
        sys.exit(1)

    with open(OUT, "w") as f:
        f.write(f"# generated by gen_target_modules.py from {config.SRC_DB}; do not edit by hand.\n")
        f.write(f"# {len(installed)} installed on 18, {len(merged)} merged away on 20, "
                f"{len(config.EXTRA_MODULES)} added ({', '.join(config.EXTRA_MODULES)}):\n")
        for m in merged:
            f.write(f"#   merged: {m}\n")
        f.write("\n".join(target) + "\n")
    print(f"merged away on 20: {len(merged)}")
    for m in merged:
        print(f"  {m}")
    print(f"wrote {OUT}: {len(target)} target modules")


if __name__ == "__main__":
    main()
