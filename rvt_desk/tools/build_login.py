def well_formed(html):
    """The generated markup is HTML; a QWeb template is XML."""
    html = re.sub(r"<(br|hr|img|input)([^<>]*?)(?<!/)>", r"<\1\2/>", html)
    etree.fromstring("<r>%s</r>" % html)
    return html


def main():
    parts = json.loads(subprocess.run(
        ["node", "-e", NODE, str(HERE / "static" / "src" / "desk")], check=True, capture_output=True, text=True).stdout)
    text = TEMPLATE % {key: well_formed(value) for key, value in parts.items()}
    etree.fromstring(text.encode())
    (HERE / "views" / "login_templates.xml").write_text(text)
    print("login template written,", len(text) // 1024, "KB")


if __name__ == "__main__":
    main()
